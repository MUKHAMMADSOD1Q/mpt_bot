def normalize_language(language: str | None) -> str:
    return language if language in SUPPORTED_LANGUAGES else "uz"


def tr(locale: str | None, key: str, **values: object) -> str:
    lang = normalize_language(locale)
    template = _TEXT[lang].get(key, _TEXT["uz"].get(key, key))
    return template.format(**values)


def menu_labels(action: str) -> tuple[str, ...]:
    key = f"menu_{action}"
    return tuple(_TEXT[lang][key] for lang in SUPPORTED_LANGUAGES)
